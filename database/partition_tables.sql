-- ============================================
-- 交易表分区表结构
-- 支持 MySQL 和 PostgreSQL
-- 
-- 分区策略：
-- 1. 按区块高度分区（每100万区块一个分区）
-- 2. 按时间分区（每月一个分区）
-- 
-- 注意：分区表需要在创建表时定义，不能对现有表直接添加分区
-- 建议：先创建新分区表，然后迁移数据
-- ============================================

